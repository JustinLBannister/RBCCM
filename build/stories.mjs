#!/usr/bin/env node
/* =========================================================================
   Storybook stories

     npm run stories                 every component and page
     npm run stories -- rbccm-hero   only the folders named

   Writes stories/components/<folder>.stories.js (one story per variant
   of the component's local preview page), stories/pages.stories.js and
   stories/catalog.json. These files are generated: edit the component,
   its preview page or its README, then run this again.

   Each story shows the preview page's own markup, styles and scripts
   (.storybook/render-preview.js), so nothing about a component is
   written twice. The docs page for a component is the "For editors and
   BAs" block from its README, and the table under it lists the editor's
   fields from the properties file.
   ========================================================================= */
import fs from 'node:fs';
import path from 'node:path';
import { catalog, ROOT } from './catalog.mjs';
import { TRANSFORMS } from './package-rules.mjs';

const OUT = path.join(ROOT, 'stories');
const COMPONENTS = path.join(OUT, 'components');
const only = process.argv.slice(2).filter((a) => !a.startsWith('-'));

const BANNER = '/* Generated by build/stories.mjs. Do not edit: change the component, its preview\n' +
  '   page or its README, then run `npm run stories`. */\n';

/* JS source for a value, plain ASCII. */
function js(value) {
  return JSON.stringify(value, null, 2)
    .replace(/</g, '\\u003c')
    .replace(/[\u007f-\uffff]/g, (c) => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'));
}

function exportName(slug, taken) {
  let name = slug.split('-').filter(Boolean).map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join('') || 'Default';
  if (!/^[A-Za-z]/.test(name)) name = 'V' + name;
  let unique = name;
  let n = 2;
  while (taken.has(unique)) unique = name + n++;
  taken.add(unique);
  return unique;
}

/* A "## Heading" section of a README, without the heading line. */
function section(text, heading) {
  const start = text.indexOf('\n## ' + heading);
  if (start === -1) return '';
  const from = text.indexOf('\n', start + 1);
  const rest = text.slice(from);
  const next = rest.search(/\n## /);
  return (next === -1 ? rest : rest.slice(0, next)).replace(/\n---\s*$/, '\n').trim();
}

function docsFor(c) {
  const parts = [];
  if (c.desc) parts.push(c.desc);
  if (c.readme) {
    const raw = fs.readFileSync(path.join(ROOT, c.readme), 'utf8');
    const text = TRANSFORMS[c.readme] ? TRANSFORMS[c.readme](raw) : raw;
    /* The deal preview skin is not shown here, so lines about it are left out. */
    const ba = section(text, 'For editors and BAs').split('\n')
      .filter((line) => !line.includes('deals-preview')).join('\n');
    if (ba) parts.push(ba);
    const where = section(text, 'TeamSite locations');
    if (where) parts.push('### TeamSite locations\n\n' + where);
  }
  parts.push('Folder: `' + c.id + '/`' + (c.preview ? ' - preview page: `' + c.preview + '`' : ''));
  return parts.join('\n\n');
}

function argTypesFor(c) {
  const out = {};
  for (const f of c.fields) {
    if (out[f.id]) continue;
    out[f.id] = {
      name: f.id,
      description: f.label || '',
      control: false,
      table: {
        type: { summary: f.options ? f.type + ' (' + f.options + ' options)' : f.type },
        defaultValue: f.value ? { summary: f.value } : undefined
      }
    };
  }
  return out;
}

const shortTitle = (c) => c.title.replace(/^RBCCM\s+/, '');
/* The id Storybook gives a component's docs page, from its title. */
const docsId = (c) => ('Components/' + c.category + '/' + shortTitle(c)).toLowerCase()
  .replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '') + '--docs';

fs.mkdirSync(COMPONENTS, { recursive: true });
if (!only.length) {
  for (const f of fs.readdirSync(COMPONENTS)) if (/\.stories\.js$/.test(f)) fs.rmSync(path.join(COMPONENTS, f));
}

let written = 0;
let stories = 0;
const skipped = [];
for (const c of catalog.components) {
  if (only.length && !only.includes(c.id)) continue;
  if (!c.preview) { skipped.push(c.id); continue; }
  const taken = new Set();
  const variants = c.variants.length ? c.variants : [{ name: 'Default', slug: '' }];
  /* Storybook reads the title and tags from the source text, so these
     keys are written plainly, not as quoted JSON. */
  let src = BANNER + "import { renderPreview } from '../../.storybook/render-preview.js';\n\n" +
    'export default {\n' +
    '  title: ' + js('Components/' + c.category + '/' + shortTitle(c)) + ',\n' +
    "  tags: ['autodocs'],\n" +
    '  parameters: ' + js({ docs: { description: { component: docsFor(c) } } }) + ',\n' +
    '  argTypes: ' + js(argTypesFor(c)) + '\n};\n';
  for (const v of variants) {
    const name = exportName(v.slug || 'default', taken);
    src += '\nexport const ' + name + ' = {\n  name: ' + js(v.name) + ',\n' +
      '  parameters: { rbccm: { file: ' + js(c.preview) + ', variant: ' + js(v.slug) + ' } },\n' +
      '  render: () => renderPreview({ file: ' + js(c.preview) + ', variant: ' + js(v.slug) + ' })\n};\n';
    stories += 1;
  }
  fs.writeFileSync(path.join(COMPONENTS, c.id + '.stories.js'), src);
  written += 1;
}

/* Pages: each build preview in a frame. */
if (!only.length || only.includes('pages')) {
  const taken = new Set();
  let src = BANNER + "import { renderFrame } from '../.storybook/render-preview.js';\n\n" +
    "export default {\n  title: 'Pages',\n  parameters: " + js({
      parameters: {
        a11y: { disable: true },
        docs: { description: { component: 'The pages built from these components. Each one is the local build preview, which loads only that page\'s own bundle. They are written by `npm run build`; if a page is blank, run the build first.' } }
      }
    }.parameters) + '\n};\n';
  for (const p of catalog.pages) {
    src += '\nexport const ' + exportName(p.name, taken) + ' = {\n  name: ' + js(p.label + (p.live ? ' (live)' : ' (in progress)')) + ',\n' +
      '  render: () => renderFrame({ src: ' + js('/' + p.preview) + ', title: ' + js(p.label) + ' })\n};\n';
  }
  fs.writeFileSync(path.join(OUT, 'pages.stories.js'), src);
}

fs.writeFileSync(path.join(OUT, 'catalog.json'), js({
  generated: catalog.generated,
  components: catalog.components.length,
  variants: catalog.components.reduce((n, c) => n + c.variants.length, 0),
  pages: catalog.pages.length,
  categories: catalog.categories.map((name) => ({
    name,
    components: catalog.components.filter((c) => c.category === name).map((c) => ({
      id: c.id,
      title: shortTitle(c),
      desc: c.desc,
      variants: c.variants.length || (c.preview ? 1 : 0),
      fields: c.fields.length,
      docs: c.preview ? docsId(c) : '',
      live: catalog.pages.filter((p) => p.live && (p.components || []).includes(c.id)).map((p) => p.label),
      building: catalog.pages.filter((p) => !p.live && (p.components || []).includes(c.id)).map((p) => p.label)
    }))
  })).filter((g) => g.components.length)
}) + '\n');

console.log('Stories written: ' + written + ' components, ' + stories + ' stories');
if (skipped.length) console.log('  no preview page, no stories: ' + skipped.join(', '));
